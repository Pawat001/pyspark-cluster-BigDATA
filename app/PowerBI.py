# ====================================================================
# STEP 1: นำเข้าเครื่องมือที่จำเป็น (Import Libraries)
# ====================================================================
# SparkSession: ใช้เป็นประตูหลักในการเปิดใช้งานและสั่งการระบบ Apache Spark
import os
from pyspark.sql import SparkSession

# GraphFrame: เครื่องมือเฉพาะทางที่ใช้จัดการและวิเคราะห์ข้อมูลในรูปแบบโครงข่าย/กราฟ
from graphframes import GraphFrame

# desc: ใช้จัดเรียงข้อมูลจากมากไปน้อย, col: ใช้ชี้ตำแหน่งคอลัมน์, lit: ใช้สร้างค่าคงที่ใส่ลงคอลัมน์
from pyspark.sql.functions import desc, col, lit


# ====================================================================
# STEP 2: เริ่มต้นระบบและตั้งค่าฐานข้อมูลกราฟ (Initialize Spark Session)
# ====================================================================
# สั่งสร้างตัวจัดการ Spark ขึ้นมา พร้อมดาวน์โหลดไฟล์เบื้องหลัง (.config) 
# เพื่อดาวน์โหลดแพ็กเกจระบบกราฟ (GraphFrames) มาติดตั้งอัตโนมัติ ป้องกันปัญหาระบบค้างนิ่ง
spark = SparkSession.builder \
    .appName("PowerBI") \
    .config("spark.jars.packages", "com.databricks:graphframes:0.8.3-spark3.5-s_2.12") \
    .getOrCreate()

# สั่งให้ระบบแสดงเฉพาะข้อความแจ้งเตือนสำคัญ (WARN) เท่านั้น 
# จะได้ไม่มีข้อความ Log ระบบทั่วไปวิ่งขึ้นมาจนบดบังหน้าจอและตารางผลลัพธ์ของเรา
spark.sparkContext.setLogLevel("WARN")


# ====================================================================
# STEP 3: โหลดข้อมูลดิบเข้าสู่ระบบ (Load Data)
# ====================================================================
# อ่านไฟล์เส้นทางการบินต้นฉบับเข้ามาเก็บไว้ในตัวแปร df (DataFrame)
# header=True -> กำหนดให้ตารางแถวแรกสุดทำหน้าที่เป็นชื่อหัวคอลัมน์
# inferSchema=True -> สั่งให้ระบบเดาประเภทข้อมูลเองอัตโนมัติ เช่น ตัวหนังสือ หรือ ตัวเลข
df = spark.read.csv("airline_routes.csv", header=True, inferSchema=True)

# สั่งให้ระบบพ่นตารางข้อมูลดิบออกมาโชว์บนหน้าจอเพื่อเช็กความถูกต้อง
df.show()


# ====================================================================
# STEP 4: เตรียมข้อมูลโหนดและเส้นเชื่อม (Prepare Vertices and Edges)
# ====================================================================
# 1. การสร้างตาราง "จุดพิกัด/สนามบิน" (Vertices หรือ Nodes)
# ระบบกราฟต้องการคอลัมน์ชื่อ "id" เพื่อระบุตัวตนของจุดนั้นๆ
# โค้ดนี้เปลี่ยนชื่อคอลัมน์ "source_airport" ให้เป็น "id" -> เลือกเอาเฉพาะคอลัมน์ id -> และตัดชื่อที่ซ้ำกันออก (distinct)
vertices = df.withColumnRenamed("source_airport", "id").select("id").distinct()

# 2. การสร้างตาราง "เส้นโยงเครือข่าย/เส้นทางการบิน" (Edges หรือ Links)
# ระบบกราฟต้องการคอลัมน์มาตรฐาน 2 ชื่อคือ "src" (ต้นทาง) และ "dst" (ปลายทาง)
# โค้ดนี้เปลี่ยน "source_airport" เป็น "src" และเปลี่ยน "destination_airport" เป็น "dst"
edges = df.withColumnRenamed("source_airport", "src").withColumnRenamed("destination_airport", "dst")

# สั่งแสดงหน้าตาตารางข้อมูลชุดโหนด (Vertices) และชุดเส้นเชื่อม (Edges) ออกมาตรวจสอบ
vertices.show()
edges.show()


# ====================================================================
# STEP 5: ประกอบร่างและตรวจสอบขนาดกราฟ (Build GraphFrame)
# ====================================================================
# นำเอาตารางจุดพิกัด (vertices) และตารางเส้นเชื่อม (edges) มารวมกันสร้างเป็นโมเดลกราฟเครือข่าย
graph = GraphFrame(vertices, edges)

# ใช้คำสั่ง .count() เพื่อนับจำนวนยอดรวมทั้งหมดของโหนดและเส้นเชื่อม แล้วสั่งพิมพ์ออกมาดู
print("จำนวนโหนด (Vertices):", graph.vertices.count())
print("จำนวนเส้นเชื่อม (Edges):", graph.edges.count())


# ====================================================================
# STEP 6: ประมวลผล คัดกรอง และแต่งสีข้อมูล (Graph Analytics & Formatting)
# ====================================================================
# นำข้อมูลเส้นบินทั้งหมด (graph.edges) มาเข้าสู่กระบวนการวิเคราะห์:
# 1. .groupBy("src", "dst").count() -> จับคู่สนามบินต้นทาง-ปลายทาง เพื่อสแกนดูว่ามีบินซ้ำกันกี่เที่ยวบิน
# 2. .filter(col("count") > 5) -> คัดเอาเฉพาะเส้นทางบินที่บินหนาแน่น หรือมีการบินซ้ำมากกว่า 5 ครั้งขึ้นไป
# 3. .orderBy(desc("count")) -> เรียงลำดับตารางข้อมูลใหม่ จากเส้นทางบินที่บินบ่อยที่สุดลงไปหาน้อยที่สุด
# 4. .withColumn("...", lit('...')) -> สร้างคอลัมน์ใหม่เพิ่มเข้าไปในตาราง เพื่อกำหนดรหัสสีที่จะเอาไปพล็อตใน PowerBI
result_df = graph.edges.groupBy("src", "dst").count() \
    .filter(col("count") > 5) \
    .orderBy(desc("count")) \
    .withColumn("source_color", lit('#3358FF')) \
    .withColumn("destination_color", lit('#FF3F33'))

# สั่งแสดงผลตารางสรุปข้อมูลขั้นสุดท้ายที่ประมวลผลเสร็จแล้วบนหน้าจอ
result_df.show()


# ====================================================================
# STEP 7: บันทึกข้อมูลเพื่อส่งออกไปใช้งาน (Export to CSV)
# ====================================================================
# กำหนดตำแหน่งพาร์ทและชื่อโฟลเดอร์ที่จะจัดเก็บไฟล์ปลายทาง
output_path = "./processed_airline_routes"

# ถ้าโฟลเดอร์ปลายทางมีอยู่แล้ว ให้ใช้โหมด append เพื่อหลีกเลี่ยงปัญหาลบโฟลเดอร์ไม่สำเร็จ
# ถ้ายังไม่มี จะใช้โหมด overwrite เพื่อให้ได้โฟลเดอร์ใหม่สะอาดๆ
write_mode = "append" if os.path.exists(output_path) else "overwrite"

# .coalesce(1) -> สั่งให้ Spark ตบรวมไฟล์ผลลัพธ์ให้รวมกันเป็น "ไฟล์เดี่ยวไฟล์เดียว" (จะได้นำเข้า PowerBI ง่ายๆ ไม่แยกชิ้น)
# .write.mode("overwrite") -> ตั้งโหมดเขียนทับ หากกดรันโค้ดซ้ำรอบสอง ระบบจะเซฟทับตัวเก่าทันทีไม่ฟ้อง Error
# .option("header", "true") -> สั่งให้ไฟล์ CSV ที่บันทึกออกมานั้น มีชื่อหัวคอลัมน์ติดไปด้วย
result_df.coalesce(1).write.mode(write_mode).option("header", "true").csv(output_path)